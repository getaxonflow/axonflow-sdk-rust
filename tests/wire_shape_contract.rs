#[derive(Deserialize, serde::Serialize, Debug, PartialEq, Eq, Clone)]
struct Drift {
    sdk_only: Fields,
    spec_only: Fields,
}

#[derive(Deserialize)]
struct Baseline {
    openapi_specs_sha: String,
    cross_spec_duplicates: BTreeMap<String, BTreeMap<String, Fields>>,
    registered_types: Vec<String>,
    per_type_drift: BTreeMap<String, Drift>,
}

struct Observed {
    commit: String,
    spec: Spec,
    registered: Vec<String>,
    drift: BTreeMap<String, Drift>,
}

fn difference(a: &[String], b: &[String]) -> Fields {
    let b: BTreeSet<&String> = b.iter().collect();
    a.iter().filter(|x| !b.contains(x)).cloned().collect()
}

fn observe() -> Observed {
    let files = snapshot_files(&snapshot_dir());
    let commit = snapshot_commit(&files).unwrap_or_else(|e| panic!("{e}"));
    let spec = load_spec(&files);
    let sdk = sdk_types();
    let mut registered = Vec::new();
    let mut drift = BTreeMap::new();
    for (name, sdk_fields) in &sdk {
        let Some(spec_fields) = spec.merged.get(name) else {
            continue;
        };
        registered.push(name.clone());
        let entry = Drift {
            sdk_only: difference(sdk_fields, spec_fields),
            spec_only: difference(spec_fields, sdk_fields),
        };
        if !entry.sdk_only.is_empty() || !entry.spec_only.is_empty() {
            drift.insert(name.clone(), entry);
        }
    }
    Observed {
        commit,
        spec,
        registered,
        drift,
    }
}

fn baseline() -> Baseline {
    let path = baseline_path();
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

const REGENERATE: &str =
    "Regenerate the baseline only for a deliberate change: see the header of tests/wire_shape_contract.rs.";

#[test]
fn the_baseline_is_pinned_to_the_snapshots_platform_commit() {
    // A baseline pinned to any other commit, such as this repository's own
    // HEAD, would name a spec the contract never read.
    let observed = observe();
    assert_eq!(
        baseline().openapi_specs_sha,
        observed.commit,
        "the baseline's openapi_specs_sha is not the commit the snapshot's headers name. {REGENERATE}"
    );
}

#[test]
fn both_sides_are_read() {
    // A reader that silently read nothing would make every other test pass.
    let observed = observe();
    assert!(
        observed.spec.merged.len() > 100,
        "only {} schemas read from the snapshot",
        observed.spec.merged.len()
    );
    assert!(
        observed
            .registered
            .iter()
            .any(|name| name == "DecideResponse"),
        "DecideResponse, a type the SDK and the spec both declare, did not match"
    );
}

#[test]
fn no_drift_outside_the_baseline() {
    let observed = observe();
    let recorded = baseline().per_type_drift;
    let mut problems = Vec::new();
    for (name, drift) in &observed.drift {
        match recorded.get(name) {
            None => problems.push(format!("  {name}: NEW drift {drift:?}")),
            Some(entry) if entry != drift => {
                problems.push(format!(
                    "  {name}: drift changed from {entry:?} to {drift:?}"
                ));
            }
            Some(_) => {}
        }
    }
    for name in recorded
        .keys()
        .filter(|name| !observed.drift.contains_key(*name))
    {
        problems.push(format!(
            "  {name}: recorded drift no longer observed; remove it so a reintroduction is caught"
        ));
    }
    assert!(
        problems.is_empty(),
        "wire-shape drift differs from the baseline:\n{}\n{REGENERATE}",
        problems.join("\n")
    );
}

#[test]
fn the_matched_types_are_the_recorded_ones() {
    // A type disappearing from either side must be a deliberate, reviewed change.
    let observed = observe();
    let recorded = baseline().registered_types;
    assert_eq!(
        observed.registered,
        recorded,
        "added: {:?}; no longer matching: {:?}. {REGENERATE}",
        difference(&observed.registered, &recorded),
        difference(&recorded, &observed.registered)
    );
}

#[test]
fn cross_spec_divergence_is_the_recorded_one() {
    let observed = observe();
    assert_eq!(
        observed.spec.cross_spec,
        baseline().cross_spec_duplicates,
        "a schema declared in several spec files diverges differently from the baseline. {REGENERATE}"
    );
}

#[test]
#[ignore = "rewrites testdata/wire_shape_baseline.json; run with WIRE_SHAPE_REFRESH=1"]
fn refresh_baseline() {
    assert_eq!(
        std::env::var(REFRESH_ENV).as_deref(),
        Ok("1"),
        "set {REFRESH_ENV}=1 to rewrite testdata/wire_shape_baseline.json"
    );
    let observed = observe();
    let baseline = serde_json::json!({
        "_comment": "Known wire-shape drift between the Rust SDK's serde types and the platform's OpenAPI schemas, pinned to the platform commit the snapshot's headers name. Generated by the ignored refresh_baseline test in tests/wire_shape_contract.rs; the tests fail on any difference from it. Burn entries down over time.",
        "openapi_specs_sha": observed.commit,
        "cross_spec_duplicates": observed.spec.cross_spec,
        "registered_types": observed.registered,
        "per_type_drift": observed.drift,
    });
    let text = serde_json::to_string_pretty(&baseline).expect("the baseline serializes") + "\n";
    fs::write(baseline_path(), text).expect("the baseline is written");
}

