/// What a field's `#[serde(...)]` attributes say about its wire name.
#[derive(Default)]
struct FieldSerde {
    rename: Option<String>,
    skip: bool,
    flatten: bool,
}

fn field_serde(attrs: &[syn::Attribute]) -> syn::Result<FieldSerde> {
    let mut out = FieldSerde::default();
    for attr in attrs.iter().filter(|a| a.path().is_ident("serde")) {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename") {
                if !meta.input.peek(syn::Token![=]) {
                    return Err(meta.error(
                        "rename(...) with separate serialize and deserialize names is not supported by this contract",
                    ));
                }
                out.rename = Some(meta.value()?.parse::<syn::LitStr>()?.value());
            } else if meta.path.is_ident("skip") {
                out.skip = true;
            } else if meta.path.is_ident("flatten") {
                out.flatten = true;
            } else if meta.input.peek(syn::Token![=]) {
                // alias, default = "...", skip_serializing_if, with, ...: none
                // changes the name a field is written under.
                meta.value()?.parse::<syn::Expr>()?;
            } else if meta.input.peek(syn::token::Paren) {
                meta.parse_nested_meta(|nested| {
                    if nested.input.peek(syn::Token![=]) {
                        nested.value()?.parse::<syn::Expr>()?;
                    }
                    Ok(())
                })?;
            }
            Ok(())
        })?;
    }
    Ok(out)
}

fn derives_serde(attrs: &[syn::Attribute]) -> syn::Result<bool> {
    let mut found = false;
    for attr in attrs.iter().filter(|a| a.path().is_ident("derive")) {
        attr.parse_nested_meta(|meta| {
            let last = meta.path.segments.last().map(|s| s.ident.to_string());
            if matches!(last.as_deref(), Some("Serialize" | "Deserialize")) {
                found = true;
            }
            Ok(())
        })?;
    }
    Ok(found)
}

/// The container attributes that change the wire names of a struct's fields,
/// which this contract refuses rather than guesses at.
fn refuse_container_serde(item: &syn::ItemStruct) -> Result<(), String> {
    for attr in item.attrs.iter().filter(|a| a.path().is_ident("serde")) {
        let mut refused = None;
        attr.parse_nested_meta(|meta| {
            for name in ["rename_all", "rename_all_fields", "tag", "transparent"] {
                if meta.path.is_ident(name) {
                    refused = Some(name);
                }
            }
            if meta.input.peek(syn::Token![=]) {
                meta.value()?.parse::<syn::Expr>()?;
            } else if meta.input.peek(syn::token::Paren) {
                meta.parse_nested_meta(|nested| {
                    if nested.input.peek(syn::Token![=]) {
                        nested.value()?.parse::<syn::Expr>()?;
                    }
                    Ok(())
                })?;
            }
            Ok(())
        })
        .map_err(|e| format!("{}: {e}", item.ident))?;
        if let Some(name) = refused {
            return Err(format!(
                "{}: #[serde({name})] changes its fields' wire names, which this contract does not model",
                item.ident
            ));
        }
    }
    Ok(())
}

/// The wire field names of a public struct that derives `Serialize` or
/// `Deserialize`, sorted; `None` for any other item.
fn wire_fields(item: &syn::ItemStruct) -> Result<Option<Fields>, String> {
    let derives = derives_serde(&item.attrs).map_err(|e| format!("{}: {e}", item.ident))?;
    if !matches!(item.vis, syn::Visibility::Public(_)) || !derives {
        return Ok(None);
    }
    let syn::Fields::Named(named) = &item.fields else {
        return Ok(None);
    };
    refuse_container_serde(item)?;
    let mut fields = Vec::new();
    for field in &named.named {
        let ident = field
            .ident
            .as_ref()
            .expect("a named field")
            .unraw()
            .to_string();
        let serde =
            field_serde(&field.attrs).map_err(|e| format!("{}.{ident}: {e}", item.ident))?;
        if serde.flatten {
            return Err(format!(
                "{}.{ident}: #[serde(flatten)] hides the wire names this contract compares",
                item.ident
            ));
        }
        if !serde.skip {
            fields.push(serde.rename.unwrap_or(ident));
        }
    }
    fields.sort();
    fields.dedup();
    Ok(Some(fields))
}

fn collect_structs(items: &[syn::Item], out: &mut Vec<(String, Fields)>) -> Result<(), String> {
    for item in items {
        match item {
            syn::Item::Struct(item) => {
                if let Some(fields) = wire_fields(item)? {
                    out.push((item.ident.to_string(), fields));
                }
            }
            syn::Item::Mod(module) => {
                if let Some((_, items)) = &module.content {
                    collect_structs(items, out)?;
                }
            }
            _ => {}
        }
    }
    Ok(())
}

fn rust_sources(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())) {
        let path = entry.expect("a directory entry").path();
        if path.is_dir() {
            rust_sources(&path, out);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            out.push(path);
        }
    }
}

/// Every public serde struct in `src/`, by name, with its wire field names.
fn sdk_types() -> BTreeMap<String, Fields> {
    let mut paths = Vec::new();
    rust_sources(&root().join("src"), &mut paths);
    paths.sort();
    let mut out: BTreeMap<String, Fields> = BTreeMap::new();
    for path in paths {
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let file = syn::parse_file(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let mut found = Vec::new();
        collect_structs(&file.items, &mut found)
            .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        for (name, fields) in found {
            if let Some(previous) = out.get(&name) {
                // Two structs of one name would make a match ambiguous.
                assert_eq!(
                    previous,
                    &fields,
                    "{name} is declared twice in src/ with different wire fields ({})",
                    path.display()
                );
            }
            out.insert(name, fields);
        }
    }
    out
}

