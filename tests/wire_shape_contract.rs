/// A key as the snapshot writes it: a JSON string.
fn key(token: &str) -> Result<String, String> {
    serde_json::from_str::<String>(token).map_err(|e| format!("{token}: not a JSON string: {e}"))
}

/// The schema declarations of one snapshot file, in order: each name with its
/// property names, or `None` for a declaration without properties.
///
/// It reads exactly the form `render()` in `scripts/snapshot_openapi_schemas.py`
/// writes, and refuses any other line. The workflow's `--check-snapshot` holds
/// the committed files to that form, so a refusal here means the reader and the
/// script disagree about it.
fn declarations(text: &str) -> Result<Vec<(String, Option<Fields>)>, String> {
    let mut out = Vec::new();
    let mut lines = text
        .lines()
        .filter(|line| !line.starts_with('#'))
        .peekable();
    if lines.next() != Some("components:") {
        return Err("expected `components:`".into());
    }
    match lines.next() {
        Some("  schemas: {}") => {
            return match lines.next() {
                None => Ok(out),
                Some(extra) => Err(format!("unexpected line after `schemas: {{}}`: {extra:?}")),
            };
        }
        Some("  schemas:") => {}
        other => return Err(format!("expected `  schemas:`, found {other:?}")),
    }
    while let Some(line) = lines.next() {
        let rest = line
            .strip_prefix("    ")
            .filter(|rest| !rest.starts_with(' '))
            .ok_or_else(|| format!("unexpected line {line:?}"))?;
        if let Some(name) = rest.strip_suffix(": {}") {
            out.push((key(name)?, None));
        } else if let Some(name) = rest.strip_suffix(':') {
            if lines.next() != Some("      properties:") {
                return Err(format!("{name}: expected `      properties:`"));
            }
            let mut fields = Vec::new();
            while let Some(field) = lines
                .peek()
                .copied()
                .and_then(|l| l.strip_prefix("        "))
            {
                let field = field
                    .strip_suffix(": {}")
                    .ok_or_else(|| format!("unexpected property line {field:?}"))?;
                fields.push(key(field)?);
                lines.next();
            }
            if fields.is_empty() {
                return Err(format!("{name}: `properties:` without a property"));
            }
            out.push((key(name)?, Some(fields)));
        } else {
            return Err(format!("unexpected line {line:?}"));
        }
    }
    Ok(out)
}

/// The spec side of the contract: every schema that declares properties.
struct Spec {
    /// Each schema's sorted property names. On a name declared in several
    /// files, the last file in name order wins.
    merged: BTreeMap<String, Fields>,
    /// Every schema declared in more than one file with DIFFERENT property
    /// sets, keyed by file. Identical redeclarations are benign.
    cross_spec: BTreeMap<String, BTreeMap<String, Fields>>,
}

fn load_spec(files: &[(String, String)]) -> Spec {
    let mut merged = BTreeMap::new();
    let mut all: BTreeMap<String, BTreeMap<String, Fields>> = BTreeMap::new();
    for (file, text) in files {
        // A later declaration of a name in one file replaces an earlier one,
        // as a YAML loader reads a repeated key.
        let mut in_file: BTreeMap<String, Option<Fields>> = BTreeMap::new();
        for (name, fields) in declarations(text).unwrap_or_else(|e| panic!("{file}: {e}")) {
            in_file.insert(name, fields);
        }
        for (name, fields) in in_file {
            let Some(mut fields) = fields else { continue };
            fields.sort();
            fields.dedup();
            all.entry(name.clone())
                .or_default()
                .insert(file.clone(), fields.clone());
            merged.insert(name, fields);
        }
    }
    let cross_spec = all
        .into_iter()
        .filter(|(_, decls)| decls.values().collect::<BTreeSet<_>>().len() > 1)
        .collect();
    Spec { merged, cross_spec }
}

/// The full platform commit every snapshot file's header names.
///
/// Each file must carry the generated header, name its own source file, and
/// name the same full 40-character commit as every other file: the same rule
/// as `snapshot_commit` in the vendored script.
fn snapshot_commit(files: &[(String, String)]) -> Result<String, String> {
    let mut commits = BTreeMap::new();
    for (file, text) in files {
        let mut lines = text.lines();
        if lines.next() != Some(HEADER_FIRST_LINE) {
            return Err(format!("{file}: missing the generated header"));
        }
        let source = lines.next().unwrap_or_default();
        let commit = source
            .strip_prefix("# Source: docs/api/")
            .and_then(|rest| rest.strip_prefix(file.as_str()))
            .and_then(|rest| rest.strip_prefix(" at platform commit "))
            .filter(|c| c.len() == 40 && c.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')))
            .ok_or_else(|| {
                format!("{file}: the header does not name this file's source and a full platform commit: {source:?}")
            })?;
        commits.insert(file.clone(), commit.to_owned());
    }
    let named: BTreeSet<&String> = commits.values().collect();
    match named.into_iter().collect::<Vec<_>>().as_slice() {
        [one] => Ok((*one).clone()),
        many => Err(format!(
            "the snapshot's files name {} platform commits: {commits:?}",
            many.len()
        )),
    }
}

