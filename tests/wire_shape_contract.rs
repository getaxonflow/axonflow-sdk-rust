//! Wire-shape contract: the platform's OpenAPI schemas against this SDK's
//! serde types.
//!
//! The platform's `docs/api` specs are the authoritative wire contract. A
//! schema-only snapshot of them is committed under `testdata/openapi/`,
//! derived by `scripts/snapshot_openapi_schemas.py` at the platform commit its
//! file headers name (see `testdata/openapi/README.md`).
//!
//! The contract reads every schema that declares properties from the snapshot,
//! and every public struct in `src/` that derives `Serialize` or `Deserialize`
//! with its wire field names (`#[serde(rename = "...")]`, else the field name).
//! For every struct whose name matches a schema, it compares the two field sets.
//!
//! Known drift is recorded in `testdata/wire_shape_baseline.json`, and the tests
//! fail on any difference from it, in either direction: new drift, drift that
//! has been burned down but is still recorded, a type that no longer matches a
//! schema, or a schema whose declarations across spec files changed. The
//! baseline is pinned to the platform commit the snapshot's headers name.
//!
//! After a deliberate change, regenerate the baseline with:
//!
//! ```text
//! WIRE_SHAPE_REFRESH=1 cargo test --test wire_shape_contract -- --ignored refresh_baseline
//! ```
//!
//! It takes the platform commit from the snapshot's headers; there is no other
//! source for it. Never regenerate to silence a failure: read it first.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;
use syn::ext::IdentExt;

/// The first line `scripts/snapshot_openapi_schemas.py` writes in every file.
const HEADER_FIRST_LINE: &str = "# GENERATED by scripts/snapshot_openapi_schemas.py - do not edit.";
const REFRESH_ENV: &str = "WIRE_SHAPE_REFRESH";

type Fields = Vec<String>;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn snapshot_dir() -> PathBuf {
    root().join("testdata").join("openapi")
}

fn baseline_path() -> PathBuf {
    root().join("testdata").join("wire_shape_baseline.json")
}

fn snapshot_files(dir: &Path) -> Vec<(String, String)> {
    let mut files: Vec<(String, String)> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|entry| entry.expect("a directory entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "yaml"))
        .map(|path| {
            let name = path
                .file_name()
                .expect("a file name")
                .to_string_lossy()
                .into_owned();
            let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{name}: {e}"));
            (name, text)
        })
        .collect();
    files.sort();
    assert!(!files.is_empty(), "{} holds no *.yaml", dir.display());
    files
}

